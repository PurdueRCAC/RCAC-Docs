# =================================================================== upstream rules


def slugify(text: str) -> str:
    """build_site.slugify: the upstream anchor and URL slug."""
    normalized = unicodedata.normalize("NFKD", text)
    ascii_text = normalized.encode("ascii", "ignore").decode("ascii")
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", ascii_text.lower()).strip("-")
    return slug or "section"


def parse_meta(text: str) -> tuple[dict[str, str], str, str]:
    """build_site.parse_meta, also returning the header comment itself."""
    match = META_COMMENT_RE.match(text)
    if not match:
        return {}, text, ""
    meta: dict[str, str] = {}
    for line in match.group(1).strip().splitlines():
        line = line.strip().rstrip(";")
        if not line:
            continue
        key, sep, value = line.partition(":")
        if not sep or not re.fullmatch(r"[a-z][a-z0-9-]*", key.strip()):
            return {}, text, ""
        meta[key.strip()] = value.strip()
    return meta, text[match.end():], match.group(0)


def order_key_for(name: str, meta: dict[str, str]) -> tuple[int, str]:
    if meta.get("order", "").isdigit():
        return int(meta["order"]), name.lower()
    match = ORDER_PREFIX_RE.match(name)
    if match:
        return int(match.group(1)), name.lower()
    return 10_000, name.lower()


def slug_for(name: str) -> str:
    stem = name[:-3] if name.lower().endswith(".md") else name
    return slugify(ORDER_PREFIX_RE.sub("", stem))


def title_from_name(name: str) -> str:
    stem = ORDER_PREFIX_RE.sub("", name[:-3] if name.lower().endswith(".md") else name)
    return stem.replace("-", " ").replace("_", " ").strip().capitalize()


def first_heading(text: str) -> str | None:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return None


def plain_text(title: str) -> str:
    """A heading as plain text, for nav labels."""
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", title)
    text = text.replace("`", "")
    text = re.sub(r"(\*\*|__)(.+?)\1", r"\2", text)
    text = re.sub(r"(?<!\w)[*_](.+?)[*_](?!\w)", r"\1", text)
    return re.sub(r"<[^>]+>", "", text).strip()


# =================================================================== source access


class Source:
    """Read-only view of the hubzero-cms repository at one commit."""

    def __init__(self, repo: Path, commit: str) -> None:
        self.repo = repo
        self.commit = commit
        if not (repo / ".git").exists() and not (repo / "HEAD").exists():
            raise ImportError_(f"$HUBZERO_CMS={repo} is not a git clone of hubzero-cms")
        probe = subprocess.run(
            ["git", "-C", str(repo), "cat-file", "-e", f"{commit}^{{commit}}"],
            capture_output=True,
        )
        if probe.returncode != 0:
            raise ImportError_(
                f"commit {commit} is not in {repo}. Fetch it with:\n"
                f"  git -C {repo} fetch --depth=1 origin {commit}"
            )
        listing = subprocess.run(
            ["git", "-C", str(repo), "ls-tree", "-r", "-z", commit],
            capture_output=True, check=True,
        ).stdout.decode("utf-8")
        self.blobs: dict[str, str] = {}
        for entry in filter(None, listing.split("\0")):
            info, path = entry.split("\t", 1)
            _mode, kind, oid = info.split()
            if kind == "blob":
                self.blobs[path] = oid
        self.dirs: set[str] = set()
        for path in self.blobs:
            parts = PurePosixPath(path).parts[:-1]
            for i in range(1, len(parts) + 1):
                self.dirs.add("/".join(parts[:i]))
        self._cache: dict[str, bytes] = {}

    def is_file(self, path: str) -> bool:
        return path in self.blobs

    def is_dir(self, path: str) -> bool:
        return path.rstrip("/") in self.dirs

    def read_bytes(self, path: str) -> bytes:
        if path not in self._cache:
            self._cache[path] = subprocess.run(
                ["git", "-C", str(self.repo), "cat-file", "blob", self.blobs[path]],
                capture_output=True, check=True,
            ).stdout
        return self._cache[path]

    def read_text(self, path: str) -> str:
        return self.read_bytes(path).decode("utf-8").replace("\r\n", "\n")

    def children(self, directory: str) -> list[tuple[str, bool]]:
        """(name, is_dir) for the direct children of a directory, sorted by name."""
        prefix = directory.rstrip("/") + "/"
        names: dict[str, bool] = {}
        for path in self.blobs:
            if path.startswith(prefix):
                rest = path[len(prefix):]
                head, sep, _ = rest.partition("/")
                names[head] = names.get(head, False) or bool(sep)
        return sorted(names.items())


# =================================================================== page model


@dataclass
class Page:
    source: str | None          # repo path, e.g. docs/tools/01-intro.md (None: synthetic section)
    output: str | None          # docs-relative path, e.g. hubzero/tools/intro.md
    title: str
    book: str | None            # book slug; None for root pages
    meta: dict[str, str] = field(default_factory=dict)
    body: str = ""
    header: str = ""
    order: tuple[int, str] = (0, "")
    children: list["Page"] = field(default_factory=list)
    is_section: bool = False
    landing: bool = False

    def walk(self) -> list["Page"]:
        pages = [self]
        for child in self.children:
            pages.extend(child.walk())
        return pages


def read_page(src: Source, path: str) -> tuple[dict[str, str], str, str, str]:
    meta, body, header = parse_meta(src.read_text(path))
    title = meta.get("title") or first_heading(body) or title_from_name(PurePosixPath(path).name)
    return meta, body, header, title


def output_for(parts: list[str], leaf: str | None, collisions: dict[str, str], source: str) -> str:
    if source in collisions:
        return collisions[source]
    base = "/".join([PAGES_DIR, *parts])
    return f"{base}/index.md" if leaf is None else f"{base}/{leaf}.md"


def load_section(src: Source, directory: str, parts: list[str], book: str,
                 collisions: dict[str, str]) -> Page:
    """build_site.load_section, producing RCAC-Docs output paths."""
    names = dict(src.children(directory))
    landing_name = next((n for n in ("README.md", "index.md") if n in names and not names[n]), None)
    dir_name = PurePosixPath(directory).name
    if landing_name:
        path = f"{directory}/{landing_name}"
        meta, body, header, title = read_page(src, path)
        section = Page(source=path, output=output_for(parts, None, collisions, path), title=title,
                       book=book, meta=meta, body=body, header=header, is_section=True)
    else:
        section = Page(source=None, output=None, title=title_from_name(dir_name), book=book,
                       is_section=True)
    section.order = order_key_for(dir_name, section.meta)
    entries: list[Page] = []
    for name, is_dir in names.items():
        if name.startswith((".", "_")) or name == "media":
            continue
        child = f"{directory}/{name}"
        if is_dir:
            if any(p.startswith(child + "/") and p.lower().endswith(".md") for p in src.blobs):
                entries.append(load_section(src, child, parts + [slug_for(name)], book, collisions))
        elif name.lower().endswith(".md") and name.lower() not in LANDING_NAMES:
            meta, body, header, title = read_page(src, child)
            leaf = Page(source=child, output=output_for(parts, slug_for(name), collisions, child),
                        title=title, book=book, meta=meta, body=body, header=header)
            leaf.order = order_key_for(name, meta)
            entries.append(leaf)
    entries.sort(key=lambda p: p.order)
    section.children = entries
    return section


@dataclass
class Model:
    config: dict
    src: Source
    books: list[Page]           # every published book, in site.json order
    roots: list[Page]           # root pages (README, STYLE, LICENSE)
    enabled: list[str]

    def pages(self) -> list[Page]:
        """Every real page that is imported now: root pages, then enabled books."""
        out = list(self.roots)
        for book in self.books:
            if book.book in self.enabled:
                out.extend(p for p in book.walk() if p.source)
        return out

    def all_pages(self) -> list[Page]:
        return list(self.roots) + [p for b in self.books for p in b.walk() if p.source]


def build_model(config: dict, src: Source) -> Model:
    collisions = dict(config.get("collisions") or {})
    enabled = list(config.get("books") or [])
    known = [b["slug"] for b in config["all_books"]]
    for slug in enabled:
        if slug not in known:
            raise ImportError_(f"import.yml: unknown book {slug!r}")
    books = []
    for entry in config["all_books"]:
        root = load_section(src, entry["dir"], [entry["slug"]], entry["slug"], collisions)
        root.title = entry["title"]     # upstream: book.root.title = site.json title
        books.append(root)
    roots = []
    for entry in config["root_pages"]:
        meta, body, header, _title = read_page(src, entry["source"])
        roots.append(Page(source=entry["source"], output=entry["output"],
                          title=first_heading(body) or entry["title"], book=None, meta=meta,
                          body=body, header=header, landing=bool(entry.get("landing"))))
    model = Model(config=config, src=src, books=books, roots=roots, enabled=enabled)
    seen: dict[str, str] = {}
    for page in model.all_pages():
        if page.output in seen:
            raise ImportError_(f"two pages map to {page.output}: {seen[page.output]} and "
                               f"{page.source}; add one to `collisions` in import.yml")
        seen[page.output] = page.source
    return model


# =================================================================== markdown scanning

FENCE_OPEN_RE = re.compile(r"^(?P<ind>[ \t]*)(?P<fence>`{3,}|~{3,})(?P<info>.*)$")
ATX_RE = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$")
LIST_RE = re.compile(r"^(?P<ind>[ \t]*)(?P<mark>[-*+]|\d{1,9}[.)])(?P<sp>[ \t]+|$)(?P<rest>.*)$")
HR_RE = re.compile(r"^ {0,3}([-*_])(?:[ \t]*\1){2,}[ \t]*$")
TABLE_ROW_RE = re.compile(r"^ {0,3}\|")
CODE_SPAN_RE = re.compile(r"(`+)(?!`)(.+?)(?<!`)\1(?!`)")


def indent_of(line: str) -> int:
    lead = line[: len(line) - len(line.lstrip(" \t"))]
    return len(lead.expandtabs(4))


def reindent(line: str, width: int) -> str:
    return " " * max(width, 0) + line.lstrip(" \t")


def line_kinds(lines: list[str]) -> list[str]:
    """Classify each line: 'fence' (inside or delimiting a fenced block), 'code'
    (indented code block), 'html' (raw HTML block), 'blank', or 'text'."""
    kinds: list[str] = []
    fence: tuple[str, int, int] | None = None
    prev = "blank"
    html = False
    for line in lines:
        if fence is not None:
            kinds.append("fence")
            m = FENCE_OPEN_RE.match(line)
            if (m and m.group("fence")[0] == fence[0] and len(m.group("fence")) >= fence[1]
                    and not m.group("info").strip()):
                fence = None
            continue
        if not line.strip():
            kinds.append("blank")
            prev, html = "blank", False
            continue
        m = FENCE_OPEN_RE.match(line)
        if m and not (m.group("fence")[0] == "`" and "`" in m.group("info")):
            fence = (m.group("fence")[0], len(m.group("fence")), indent_of(line))
            kinds.append("fence")
            prev = "fence"
            continue
        if html:
            kinds.append("html")
            continue
        if prev in ("blank", "code") and indent_of(line) >= 4 and (not kinds or _top_level(lines, len(kinds))):
            kinds.append("code")
            prev = "code"
            continue
        if indent_of(line) <= 3 and re.match(r"^\s*<(?!!--\s*include)[A-Za-z!/]", line):
            html = True
            kinds.append("html")
            prev = "html"
            continue
        kinds.append("text")
        prev = "text"
    return kinds


def _top_level(lines: list[str], index: int) -> bool:
    """True if the nearest preceding non-blank text is not inside a list item,
    so a 4-space-indented line there is an indented code block."""
    for line in reversed(lines[:index]):
        if not line.strip():
            continue
        if LIST_RE.match(line) and not HR_RE.match(line):
            return False
        if indent_of(line) == 0:
            return True
    return True


def mask_code_spans(line: str) -> str:
    """Blank out inline code so links inside it are not rewritten."""
    return CODE_SPAN_RE.sub(lambda m: "\0" * len(m.group(0)), line)


# =================================================================== transforms


def expand_includes(text: str, src: Source, warn) -> str:
    """build_site.expand_includes, reading from the pinned commit.

    Unlike upstream, a directive inside a fenced or indented code block is left
    alone: STYLE.md shows the directive itself in a ```markdown fence, and
    expanding it there nests fences and breaks the rest of the page."""
    lines = text.split("\n")
    kinds = line_kinds(lines)
    return "\n".join(
        line if kind in ("fence", "code") else _expand_line(line, src, warn)
        for line, kind in zip(lines, kinds)
    )


def _expand_line(text: str, src: Source, warn) -> str:

    def replace(match: re.Match[str]) -> str:
        spec = match.group(1).strip()
        rel, _, span = spec.partition(":")
        if not src.is_file(rel):
            warn(f"include of missing file {rel!r}")
            return match.group(0)
        lines = src.read_text(rel).splitlines()
        if span:
            start, _, end = span.partition("-")
            lines = lines[max(int(start) - 1, 0): int(end or len(lines))]
        # A directive indented into a list item keeps the whole block there.
        ind = text[: len(text) - len(text.lstrip(" \t"))] if text.lstrip().startswith("<!--") else ""
        body = "\n".join(ind + ln if ln.strip() else "" for ln in lines).rstrip("\n")
        lang = INCLUDE_LANGS.get(PurePosixPath(rel).suffix, "")
        return f"```{lang}\n{body}\n{ind}```"

    return INCLUDE_RE.sub(replace, text)


LINK_DEST_RE = re.compile(
    r"(?P<pre>\]\(\s*)(?P<dest><[^<>\n]*>|[^\s()<>]*(?:\([^\s()]*\)[^\s()<>]*)*)"
    r"(?P<post>(?:\s+(?:\"[^\"]*\"|'[^']*'|\([^)]*\)))?\s*\))"
)
REF_DEF_RE = re.compile(r"^(?P<pre> {0,3}\[[^\]]+\]:[ \t]*)(?P<dest><[^>]*>|\S+)(?P<post>.*)$")
HTML_ATTR_RE = re.compile(r"""(?P<attr>\b(?:href|src|srcset)\s*=\s*)(?P<q>["'])(?P<url>[^"']*)(?P=q)""")


def pages_path(output: str) -> str:
    """A page's URL path under /hubzero/, as hubzero.github.io lays it out ('' is the landing)."""
    rel = output[len(PAGES_DIR) + 1:]
    if rel == "index.md":
        return ""
    if rel.endswith("/index.md"):
        return rel[: -len("index.md")]
    return rel[: -len(".md")] + "/"


BARE_URL_RE = re.compile(r"https?://[^\s<>()\[\]\"'`]+")


class Resolver:
    """build_site.make_link_resolver, rewritten for RCAC-Docs (PLAN §2, transform 3-4)."""

    def __init__(self, model: Model, page: Page, warn) -> None:
        self.model = model
        self.page = page
        self.warn = warn
        self.src = model.src
        commit = model.config["commit"]
        base = model.config["repo"].rstrip("/")
        self.blob_base = f"{base}/blob/{commit}"
        self.tree_base = f"{base}/tree/{commit}"
        self.by_source = {p.source: p for p in model.all_pages()}
        self.assets: set[str] = set()
        self.fallbacks = 0
        # GOAL R12: references to the GitHub Pages site point here instead.
        pages_url = model.config.get("pages_url", "").rstrip("/")
        self.pages_re = (re.compile(r"https?://" + re.escape(pages_url.split("://", 1)[-1])
                                    + r"(?=/|#|$)", re.I) if pages_url else None)
        self.by_pages_path = {pages_path(p.output): p for p in model.all_pages() if p.output}
        self.pages_rewrites = 0

    def _pages_target(self, href: str) -> tuple["Page", str] | None:
        rest = self.pages_re.sub("", href, count=1).lstrip("/")
        path, _sep, fragment = rest.partition("#")
        target = (self.model.config.get("pages_targets") or {}).get(path)
        if target:
            source, _s, default_fragment = target.partition("#")
            page = self.by_source.get(source)
            fragment = fragment or default_fragment
        else:
            page = self.by_pages_path.get(path if not path or path.endswith("/") else path + "/")
        if page is None:
            self.warn(f"GitHub Pages link with no page here {href!r}")
            return None
        self.pages_rewrites += 1
        return page, fragment

    def pages_link(self, href: str) -> str:
        """A GitHub Pages link → a relative link to the same page here."""
        hit = self._pages_target(href)
        if hit is None:
            return href
        dest, fragment = hit
        if dest is self.page and fragment:
            return f"#{fragment}"
        if dest.book is None or dest.book in self.model.enabled:
            out = os.path.relpath(dest.output, os.path.dirname(self.page.output)).replace(os.sep, "/")
        else:
            self.fallbacks += 1
            out = f"{self.blob_base}/{dest.source}"
        return out + (f"#{fragment}" if fragment else "")

    def pages_absolute(self, url: str) -> str:
        """A bare GitHub Pages URL in prose → the same page's absolute URL here."""
        hit = self._pages_target(url)
        if hit is None:
            return url
        dest, fragment = hit
        base = self.model.config["site_url"].rstrip("/")
        return f"{base}/{pages_path(dest.output)}" + (f"#{fragment}" if fragment else "")

    def _prefix_insensitive(self, candidate: str) -> str | None:
        def norm(part: str) -> str:
            return "readme.md" if part.lower() == "readme.md" else slug_for(part)
        want = [norm(p) for p in PurePosixPath(candidate).parts]
        for known in sorted(self.by_source):
            parts = PurePosixPath(known).parts
            if len(parts) == len(want) and all(norm(p) == w for p, w in zip(parts, want)):
                return known
        return None

    def __call__(self, href: str) -> str:
        if not href or href.startswith(("#", "//")):
            return href
        if self.pages_re and self.pages_re.match(href):
            return self.pages_link(href)
        if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", href):
            return href
        path_part, sep, fragment = href.partition("#")
        if not path_part:
            return href
        source_dir = PurePosixPath(self.page.source).parent
        target = os.path.normpath(str(source_dir / unquote(path_part))).replace(os.sep, "/")
        if target.startswith(".."):
            self.warn(f"link outside the repository {href!r}")
            return href
        candidates = [target]
        if not target.lower().endswith(".md"):
            candidates += [f"{target.rstrip('/')}/README.md", f"{target.rstrip('/')}/index.md"]
        for candidate in candidates:
            found = candidate if candidate in self.by_source else self._prefix_insensitive(candidate)
            if found is None:
                continue
            dest = self.by_source[found]
            if dest.book is None or dest.book in self.model.enabled:
                rel = os.path.relpath(dest.output, os.path.dirname(self.page.output))
                return rel.replace(os.sep, "/") + sep + fragment
            self.fallbacks += 1
            return f"{self.blob_base}/{dest.source}" + sep + fragment
        if (target.startswith("docs/") and self.src.is_file(target)
                and PurePosixPath(target).suffix.lower() in COPIED_SUFFIXES):
            self.assets.add(target)
            return f"/{ASSETS_DIR}/{target[len('docs/'):]}" + sep + fragment
        if self.src.is_file(target):
            return f"{self.blob_base}/{target}" + sep + fragment
        if self.src.is_dir(target):
            return f"{self.tree_base}/{target.rstrip('/')}" + sep + fragment
        # A source file missing at the commit (an upstream defect): link its
        # nearest existing directory, so the link still lands somewhere real.
        parent = PurePosixPath(target).parent
        while str(parent) not in ("", ".") and not self.src.is_dir(str(parent)):
            parent = parent.parent
        if str(parent) not in ("", "."):
            self.warn(f"link to missing file {path_part!r}; linked its directory {str(parent)!r}")
            return f"{self.tree_base}/{parent}"
        self.warn(f"link to missing file {path_part!r}")
        return href

    def srcset(self, value: str) -> str:
        out = []
        for candidate in value.split(","):
            stripped = candidate.strip()
            if stripped:
                url, _, descriptor = stripped.partition(" ")
                out.append(f"{self(url)} {descriptor.strip()}".strip())
        return ", ".join(out)


def rewrite_links(lines: list[str], kinds: list[str], resolve: Resolver) -> list[str]:
    out = []
    for line, kind in zip(lines, kinds):
        if kind in ("fence", "code", "blank"):
            out.append(line)
            continue
        masked = mask_code_spans(line)
        pieces: list[tuple[int, int, str]] = []

        def take(match: re.Match[str], group: str, new: str) -> None:
            pieces.append((match.start(group), match.end(group), new))

        if kind == "text":
            ref = REF_DEF_RE.match(masked)
            if ref:
                dest = ref.group("dest")
                inner = dest[1:-1] if dest.startswith("<") else dest
                new = resolve(inner)
                take(ref, "dest", f"<{new}>" if dest.startswith("<") else new)
            else:
                for m in LINK_DEST_RE.finditer(masked):
                    dest = m.group("dest")
                    inner = dest[1:-1] if dest.startswith("<") else dest
                    new = resolve(inner)
                    if new != inner:
                        take(m, "dest", f"<{new}>" if dest.startswith("<") else new)
        for m in HTML_ATTR_RE.finditer(masked):
            url = m.group("url")
            new = resolve.srcset(url) if "srcset" in m.group("attr").lower() else resolve(url)
            if new != url:
                take(m, "url", new)
        for start, end, new in sorted(pieces, reverse=True):
            line = line[:start] + new + line[end:]
        out.append(line)
    return out


def rewrite_pages_text(lines: list[str], kinds: list[str], resolve: Resolver) -> list[str]:
    """Bare GitHub Pages URLs left in prose after rewrite_links → this site (GOAL R12)."""
    if resolve.pages_re is None:
        return lines
    out = []
    for line, kind in zip(lines, kinds):
        if kind in ("fence", "code", "blank"):
            out.append(line)
            continue
        masked = mask_code_spans(line)
        pieces = []
        for m in BARE_URL_RE.finditer(masked):
            url = m.group(0).rstrip(".,;:!?")
            if resolve.pages_re.match(url):
                pieces.append((m.start(), m.start() + len(url), resolve.pages_absolute(url)))
        for start, end, new in sorted(pieces, reverse=True):
            line = line[:start] + new + line[end:]
        out.append(line)
    return out


_PM = markdown.Markdown(extensions=["toc", "attr_list"])


def pm_base_id(heading_line: str) -> str:
    """The id Python-Markdown's toc gives this heading line on its own."""
    _PM.reset()
    html = _PM.convert(heading_line)
    m = re.search(r'<h[1-6][^>]*\bid="([^"]*)"', html)
    return m.group(1) if m else ""


def upstream_text(raw: str) -> str:
    """The heading text upstream slugifies: markdown-it inline content, tags and backticks removed."""
    return re.sub(r"<[^>]+>", "", raw).strip().replace("`", "")


def add_heading_ids(lines: list[str], kinds: list[str]) -> tuple[list[str], int]:
    """Append `{ #<upstream id> }` where Python-Markdown's id would differ (PLAN §2, transform 5)."""
    heads = []   # (index, level, upstream id, python-markdown base id, ends in brace)
    counts: dict[str, int] = {}
    for i, (line, kind) in enumerate(zip(lines, kinds)):
        if kind != "text":
            continue
        m = ATX_RE.match(line)
        if not m or not (m.group(2) or "").strip():
            continue
        text = upstream_text(m.group(2))
        if not text:
            continue
        base = slugify(text)
        n = counts.get(base, 0)
        counts[base] = n + 1
        up = base if n == 0 else f"{base}-{n + 1}"
        heads.append((i, len(m.group(1)), up, pm_base_id(line.strip()), line.rstrip().endswith("}")))
    explicit = {i for i, level, _up, _pm, brace in heads if brace and level > 1}
    while True:
        used = {up for i, _l, up, _p, _b in heads if i in explicit}
        changed = False
        for i, level, up, pm, _brace in heads:
            if i in explicit:
                continue
            got = pm_unique(pm, used) if pm else ""
            if got != up and level > 1:
                explicit.add(i)
                changed = True
                break
            used.add(got)
        if not changed:
            break
    out = list(lines)
    for i, _level, up, _pm, _brace in heads:
        if i in explicit:
            out[i] = out[i].rstrip() + f" {{ #{up} }}"
    return out, len(explicit)


CALLOUT_RE = re.compile(
    r"^(?P<ind>[ \t]*)>[ \t]?\*\*(?P<label>note|tip|warning|important|caution):?\*\*:?[ \t]*(?P<rest>.*)$",
    re.I,
)
QUOTE_RE = re.compile(r"^(?P<ind>[ \t]*)>[ \t]?(?P<rest>.*)$")


def starts_block(line: str) -> bool:
    """True if the line opens a block (list item, heading, fence, rule), so it
    ends a blockquote instead of continuing it lazily, as in CommonMark."""
    return bool(LIST_RE.match(line) or ATX_RE.match(line) or HR_RE.match(line)
                or FENCE_OPEN_RE.match(line))


def convert_callouts(lines: list[str], kinds: list[str]) -> tuple[list[str], int]:
    """`> **Note:** …` blockquotes → Material admonitions (`!!! note`).

    Upstream's _apply_admonitions turns a blockquote whose first bold run is
    one of Note/Tip/Warning/Important/Caution into a styled callout (STYLE.md,
    "Notes and warnings"). Material has the same five types (important and
    caution are aliases of tip and warning), so the label becomes the type and
    its default title, and leaves the body. Any other blockquote is untouched."""
    out: list[str] = []
    count = 0
    i = 0
    while i < len(lines):
        m = CALLOUT_RE.match(lines[i]) if kinds[i] == "text" else None
        if not m:
            out.append(lines[i])
            i += 1
            continue
        ind = m.group("ind")
        body = [m.group("rest")]
        i += 1
        while i < len(lines) and kinds[i] == "text":
            q = QUOTE_RE.match(lines[i])
            if q and q.group("ind") == ind:
                body.append(q.group("rest"))
            elif not (lines[i].lstrip().startswith(">") or starts_block(lines[i])):
                body.append(lines[i].strip())      # lazy continuation
            else:
                break
            i += 1
        if out and out[-1].strip():
            out.append("")
        out.append(f"{ind}!!! {m.group('label').lower()}")
        out.extend(f"{ind}    {b}" if b.strip() else "" for b in body)
        count += 1
    return out, count


def normalize_dialect(lines: list[str], kinds: list[str]) -> tuple[list[str], dict[str, int]]:
    """Mechanical CommonMark → Python-Markdown fixes (PLAN §2, transform 6):
    list-item content re-indented to 4 spaces per level, a blank line inserted
    before a top-level list that directly follows a paragraph, and a blank line
    inserted where a block (heading, list, fence, quote, HTML) directly follows a
    table row. GFM ends a table there; Python-Markdown reads the block as a row.
    Also a blank line before a list item that directly follows a later paragraph
    of the previous item: Python-Markdown reads the marker as paragraph text. The
    item is already loose (that paragraph follows a blank line), so the list
    renders with the same spacing."""
    out: list[str] = []
    stats = {"reindented": 0, "blank-before-list": 0, "blank-after-table": 0,
             "blank-between-items": 0}
    stack: list[tuple[int, int]] = []       # (original content column, delta)
    fence_delta: tuple[int, int] | None = None   # (threshold column, delta) inside a fence
    prev = "blank"
    later_para = False      # the current text began after a blank line inside a list

    def delta_for(col: int) -> tuple[int, int]:
        for c, d in reversed(stack):
            if col >= c:
                return c, d
        return 0, 0

    for line, kind in zip(lines, kinds):
        if kind == "fence" and fence_delta is not None:
            thr, d = fence_delta
            new = reindent(line, indent_of(line) + d) if (line.strip() and d and indent_of(line) >= thr) else line
            stats["reindented"] += new != line
            out.append(new)
            if FENCE_OPEN_RE.match(line) and prev == "fence-body":
                fence_delta = None
                prev = "fence"
            else:
                prev = "fence-body"
            continue
        if kind == "blank":
            out.append(line)
            prev = "blank"
            continue
        lead = indent_of(line)
        is_quote = line.lstrip().startswith(">")
        m = None if (kind != "text" or is_quote or HR_RE.match(line)) else LIST_RE.match(line)
        interrupts = bool(m) or kind in ("fence", "html") or is_quote or bool(ATX_RE.match(line)) or bool(HR_RE.match(line))
        in_list = bool(stack)
        if prev == "table" and interrupts:
            out.append("")
            stats["blank-after-table"] += 1
        if prev == "blank" or interrupts:
            while stack and lead < stack[-1][0]:
                stack.pop()
        _c, d = delta_for(lead)
        if m:
            if not in_list and prev == "text":
                out.append("")
                stats["blank-before-list"] += 1
            elif in_list and prev == "text" and later_para:
                out.append("")
                stats["blank-between-items"] += 1
            spaces = len(m.group("sp").expandtabs(4))
            width = len(m.group("mark"))
            content = lead + width + (1 if (not m.group("rest") or spaces > 4) else spaces)
            new_base = lead + d
            stack.append((content, new_base + 4 - content))
        new = reindent(line, lead + d) if d else line
        stats["reindented"] += new != line
        out.append(new)
        if kind == "fence":
            thr, dd = delta_for(lead)
            fence_delta = (thr, dd)
            prev = "fence-open"
            continue
        if m:
            prev = "item"
        elif kind == "text" and TABLE_ROW_RE.match(line):
            prev = "table"
        elif kind == "text" and not ATX_RE.match(line):
            if prev != "text":
                later_para = prev == "blank" and bool(stack)
            prev = "text"
        else:
            prev = "other"
    return out, stats


SHORTCODE_RE = re.compile(r":(?=[+\-\w]+:)")
HTML_TAG_RE = re.compile(r"<[^>\n]*>")


def neutralize_shortcodes(lines: list[str], kinds: list[str]) -> tuple[list[str], int]:
    """Keep `:word:` text literal. The site enables pymdownx.emoji, so prose such
    as `HH:mm:ss` would render `:mm:` as a flag; upstream renders no emoji at all.
    The opening colon of each shortcode-shaped run becomes `&#58;`, outside code
    spans, link destinations, bare URLs and HTML tags."""
    out: list[str] = []
    count = 0
    for line, kind in zip(lines, kinds):
        if kind != "text" or ":" not in line:
            out.append(line)
            continue
        masked = mask_code_spans(line)
        for rx in (LINK_DEST_RE, HTML_TAG_RE, BARE_URL_RE):
            masked = rx.sub(lambda m: "\0" * len(m.group(0)), masked)
        hits = []
        for m in SHORTCODE_RE.finditer(masked):
            end = masked.find(":", m.end())
            if hits and m.start() < hits[-1][1]:
                continue
            hits.append((m.start(), end))
        for start, _end in reversed(hits):
            line = line[:start] + "&#58;" + line[start + 1:]
        count += len(hits)
        out.append(line)
    return out, count


def unescape_table_code_pipes(lines: list[str], kinds: list[str]) -> tuple[list[str], int]:
    """In a table row, `\\|` inside a code span is CommonMark's way to keep the
    pipe from splitting the cell. Python-Markdown already ignores pipes inside
    code spans and would print the backslash, so drop it there."""
    out: list[str] = []
    count = 0
    for line, kind in zip(lines, kinds):
        if kind == "text" and TABLE_ROW_RE.match(line) and "\\|" in line:
            new = CODE_SPAN_RE.sub(lambda m: m.group(0).replace("\\|", "|"), line)
            count += new != line
            line = new
        out.append(line)
    return out, count


OL_ITEM_RE = re.compile(r"^(\d{1,9})[.)][ \t]")


def continue_ordered_lists(lines: list[str], kinds: list[str]) -> tuple[list[str], int]:
    """Python-Markdown ignores an ordered list's start number, so a top-level list
    that resumes after a block (step 3, a table, then step 4) restarts at 1. When
    item n+1 follows item n with only non-heading blocks in between, those blocks
    are indented into item n, so the numbering carries on. Upstream renders the
    same steps as `<ol start="n+1">`."""
    out = list(lines)
    count = 0
    last_n: int | None = None
    gap_start: int | None = None     # first top-level non-list line after item n
    for i, (line, kind) in enumerate(zip(lines, kinds)):
        if not line.strip():        # blank, including blank lines inside a fence
            continue
        top = indent_of(line) == 0
        m = OL_ITEM_RE.match(line) if (kind == "text" and top) else None
        if m:
            n = int(m.group(1))
            if gap_start is not None and last_n is not None and n == last_n + 1:
                for j in range(gap_start, i):
                    if out[j].strip():
                        out[j] = "    " + out[j]
                count += 1
            last_n, gap_start = n, None
            continue
        if not top:
            continue
        if ATX_RE.match(line) or HR_RE.match(line) or (kind == "text" and LIST_RE.match(line)):
            last_n, gap_start = None, None
        elif last_n is not None and gap_start is None:
            gap_start = i
    return out, count


def front_matter(page: Page, commit: str) -> str:
    fm: dict = {"tags": ["HUBzero"], "render_macros": False}
    if page.landing:
        fm["hide"] = ["footer"]
    if page.meta.get("summary"):
        fm["description"] = page.meta["summary"]
    hz = {"upstream": page.source, "commit": commit, "status": page.meta.get("status", "")}
    for key, value in page.meta.items():
        if key != "status":
            hz[key] = value
    fm["hubzero"] = hz
    return "---\n" + yaml.safe_dump(fm, sort_keys=False, allow_unicode=True,
                                     default_flow_style=False, width=4096) + "---\n"


def about_block(config: dict, text: str) -> str:
    """Provenance for the landing page. README.md already ends with an "About the
    documentation" section (writing guide, license, status), so the paragraph joins
    it there; otherwise it gets its own section."""
    commit = config["commit"]
    repo = config["repo"].rstrip("/")
    para = (
        "These pages are the documentation of the [HUBzero](https://hubzero.org) platform. "
        "They were imported into the RCAC documentation from the `docs/` directory of "
        f"the [hubzero-cms repository]({repo}) at commit "
        f"[`{commit[:8]}`]({repo}/tree/{commit}/docs), and the HUBzero team maintains them "
        "here. Like the HUBzero code, they are released under the [MIT License](license.md).\n"
    )
    h2 = [ln for ln in text.split("\n") if ln.startswith("## ")]
    if h2 and h2[-1][3:].strip().lower().startswith("about"):
        return "\n" + para
    return "\n## About this documentation\n\n" + para


@dataclass
class Result:
    files: dict[str, bytes]          # docs-relative path -> bytes (pages and assets)
    nav: str                         # the nav region, markers included
    warnings: list[str]
    stats: dict[str, int]
    unreferenced: list[str]


def convert(model: Model, page: Page, warnings: list[str], stats: dict[str, int],
            assets: set[str]) -> bytes:
    def warn(message: str) -> None:
        warnings.append(f"{page.source}: {message}")

    body = expand_includes(page.body, model.src, warn)
    lines = body.lstrip("\n").split("\n")
    kinds = line_kinds(lines)
    resolver = Resolver(model, page, warn)
    lines = rewrite_links(lines, kinds, resolver)
    lines = rewrite_pages_text(lines, kinds, resolver)
    assets |= resolver.assets
    stats["github-fallback-links"] += resolver.fallbacks
    stats["github-pages-refs"] += resolver.pages_rewrites
    lines, n_ids = add_heading_ids(lines, kinds)
    stats["explicit-heading-ids"] += n_ids
    lines, n_callouts = convert_callouts(lines, kinds)
    stats["callouts"] += n_callouts
    kinds = line_kinds(lines)
    lines, n_codes = neutralize_shortcodes(lines, kinds)
    stats["shortcodes"] += n_codes
    lines, n_pipes = unescape_table_code_pipes(lines, kinds)
    stats["table-code-pipes"] += n_pipes
    lines, dialect = normalize_dialect(lines, kinds)
    for key, value in dialect.items():
        stats[key] += value
    kinds = line_kinds(lines)
    lines, n_resumed = continue_ordered_lists(lines, kinds)
    stats["resumed-lists"] += n_resumed
    text = "\n".join(lines).rstrip("\n") + "\n"
    if page.landing:
        text += about_block(model.config, text)
    return (front_matter(page, model.config["commit"]) + "\n" + text).encode("utf-8")


def q(label: str) -> str:
    return '"' + label.replace("\\", "\\\\").replace('"', '\\"') + '"'


def nav_lines(node: Page, depth: int) -> list[str]:
    pad = "  " * depth
    if not node.children:
        return [f"{pad}- {q(plain_text(node.title))}: {node.output}"]
    lines = [f"{pad}- {q(plain_text(node.title))}:"]
    if node.output:
        lines.append(f"{pad}  - {node.output}")
    for child in node.children:
        lines.extend(nav_lines(child, depth + 1))
    return lines


def build_nav(model: Model) -> str:
    landing = next(p for p in model.roots if p.landing)
    lines = [NAV_BEGIN, f"  - {q(NAV_TITLE)}:", f"    - {landing.output}"]
    for book in model.books:
        if book.book in model.enabled:
            lines.extend(nav_lines(book, 2))
    others = [p for p in model.roots if not p.landing]
    if others:
        lines.append(f"    - {q(ABOUT_GROUP)}:")
        title_of = {e["source"]: e["title"] for e in model.config["root_pages"]}
        for page in others:
            lines.append(f"      - {q(title_of[page.source])}: {page.output}")
    lines.append(NAV_END)
    return "\n".join(lines) + "\n"


def run_import(model: Model) -> Result:
    warnings: list[str] = []
    stats = {"pages": 0, "assets": 0, "github-fallback-links": 0, "github-pages-refs": 0,
             "explicit-heading-ids": 0, "callouts": 0, "reindented": 0, "blank-before-list": 0,
             "blank-after-table": 0, "blank-between-items": 0, "shortcodes": 0,
             "table-code-pipes": 0, "resumed-lists": 0}
    assets: set[str] = set()
    files: dict[str, bytes] = {}
    for page in model.pages():
        files[page.output] = convert(model, page, warnings, stats, assets)
        stats["pages"] += 1
    for asset in sorted(assets):
        files[f"{ASSETS_DIR}/{asset[len('docs/'):]}"] = model.src.read_bytes(asset)
    stats["assets"] = len(assets)
    unreferenced = []
    for book in model.books:
        if book.book in model.enabled:
            prefix = f"docs/{book.book}/"
            for path in sorted(model.src.blobs):
                if (path.startswith(prefix) and not path.lower().endswith(".md")
                        and path not in assets):
                    unreferenced.append(path)
    return Result(files=files, nav=build_nav(model), warnings=warnings, stats=stats,
                  unreferenced=unreferenced)


