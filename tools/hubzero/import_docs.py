def load_model() -> Model:
    config = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    repo = os.environ.get("HUBZERO_CMS")
    if not repo:
        raise ImportError_("set HUBZERO_CMS to a local clone of " + config["repo"])
    return build_model(config, Source(Path(repo).expanduser(), config["commit"]))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("import", help="regenerate docs/hubzero/, its images, and the nav region")
    check = sub.add_parser("check", help="acceptance gate: re-import, compare, and check site/")
    check.add_argument("--final", action="store_true",
                       help="also require all five books, 416 pages, and the home-page card")
    args = parser.parse_args(argv)
    try:
        model = load_model()
        result = run_import(model)
    except ImportError_ as exc:
        print(f"import_docs: {exc}", file=sys.stderr)
        return 2
    if args.command == "import":
        write_import(result)
        s = result.stats
        print(f"Imported {s['pages']} pages and {s['assets']} assets from {model.config['commit'][:8]} "
              f"(books: {', '.join(model.enabled) or 'none'}).")
        print(f"  explicit heading ids: {s['explicit-heading-ids']}; callouts: {s['callouts']}; "
              f"list lines re-indented: "
              f"{s['reindented']}; blank lines before lists: {s['blank-before-list']}; "
              f"links to not-yet-imported pages (GitHub): {s['github-fallback-links']}")
        if result.unreferenced:
            print(f"  {len(result.unreferenced)} unreferenced files in enabled books (not copied):")
            for path in result.unreferenced:
                print(f"    {path}")
        for warning in result.warnings:
            print(f"  warning: {warning}")
        print("Next: .venv/bin/python tools/generate_breadcrumbs.py")
        return 0
    findings = run_check(model, result, args.final)
    for warning in result.warnings:
        print(f"note: {warning}")
    if findings:
        for finding in findings:
            print(f"FAIL {finding}")
        print(f"check: {len(findings)} finding(s)")
        return 1
    print(f"check: PASS ({len(model.pages())} pages; books: {', '.join(model.enabled) or 'none'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
