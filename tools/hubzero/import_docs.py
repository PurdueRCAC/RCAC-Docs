def split_nav_region(text: str) -> tuple[str, str | None, str]:
    """(before, region-or-None, after). Without markers, split before `Contact us`."""
    begin = text.find(NAV_BEGIN + "\n")
    if begin >= 0:
        end = text.find(NAV_END + "\n", begin)
        if end < 0:
            raise ImportError_("mkdocs.yml: hubzero nav begin marker without end marker")
        end += len(NAV_END) + 1
        return text[:begin], text[begin:end], text[end:]
    anchor = text.find(NAV_ANCHOR + "\n")
    if anchor < 0:
        raise ImportError_(f"mkdocs.yml: cannot find {NAV_ANCHOR.strip()!r} to place the nav")
    return text[:anchor], None, text[anchor:]


def write_import(result: Result) -> None:
    for top in (DOCS / PAGES_DIR, DOCS / ASSETS_DIR):
        if top.exists():
            shutil.rmtree(top)
    for rel, data in sorted(result.files.items()):
        path = DOCS / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    text = MKDOCS_YML.read_text(encoding="utf-8")
    before, _region, after = split_nav_region(text)
    MKDOCS_YML.write_text(before + result.nav + after, encoding="utf-8", newline="\n")


