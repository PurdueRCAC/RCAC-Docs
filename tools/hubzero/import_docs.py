#!/usr/bin/env python3
"""Import the HUBzero documentation into RCAC-Docs, and check the result.

Usage (from the repo root):

    HUBZERO_CMS=/path/to/hubzero-cms .venv/bin/python tools/hubzero/import_docs.py import
    HUBZERO_CMS=/path/to/hubzero-cms .venv/bin/python tools/hubzero/import_docs.py check [--final]

`import` regenerates docs/hubzero/**, docs/assets/images/hubzero/**, and the
HUBzero region of the mkdocs.yml nav from the hubzero-cms repository at the
commit pinned in tools/hubzero/import.yml. It reads every file with `git`
at that commit, never from the clone's working tree, so the output depends
only on the commit and this script.

`check` is the acceptance gate (spec/hubzero-docs/GOAL.md R2-R8). It
re-imports in memory and compares byte-for-byte with what is committed, then
checks the pages themselves and, after `mkdocs build`, the built site/hubzero/.

The rules mirror hubzero-cms gh-pages/build_site.py (parse_meta, order_key_for,
slug_for, slugify, expand_includes, make_link_resolver, and the heading ids),
so the port shows what hubzero.github.io shows. See tools/hubzero/README.md.
"""

