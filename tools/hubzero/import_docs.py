class SiteParser(HTMLParser):
    """Collect ids anywhere, and links and images inside <article>."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.ids: set[str] = set()
        self.links: list[str] = []
        self.images: list[tuple[str, str | None]] = []
        self.h2: list[tuple[str, str]] = []
        self.h1: list[str] = []
        self._article = 0
        self._heading: tuple[str, str, list[str]] | None = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if a.get("id"):
            self.ids.add(a["id"])
        if tag == "article":
            self._article += 1
        if not self._article:
            return
        if tag == "a" and a.get("href") is not None and "headerlink" not in (a.get("class") or ""):
            self.links.append(a["href"])
        elif tag == "img":
            self.images.append((a.get("src") or "", a.get("alt")))
        elif tag in ("h1", "h2"):
            self._heading = (tag, a.get("id") or "", [])
        elif tag == "a" and self._heading is not None:
            self._heading[2].append("\0")   # permalink anchor: ignore its text

    def handle_endtag(self, tag):
        if tag == "article" and self._article:
            self._article -= 1
        if self._heading is not None and tag == self._heading[0]:
            text = "".join(self._heading[2]).split("\0")[0].strip()
            if tag == "h1":
                self.h1.append(text)
            else:
                self.h2.append((self._heading[1], text))
            self._heading = None

    def handle_data(self, data):
        if self._heading is not None:
            self._heading[2].append(data)


def site_path_for(output: str) -> Path:
    stem = output[:-3]
    if stem.endswith("/index") or stem == "index":
        return SITE / stem.rsplit("index", 1)[0] / "index.html"
    return SITE / stem / "index.html"


def split_front_matter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end < 0:
        return {}, text
    return yaml.safe_load(text[4:end]) or {}, text[end + 5:]


def run_check(model: Model, result: Result, final: bool) -> list[str]:
    findings: list[str] = []
    find = findings.append

    # R8: a re-import reproduces what is committed, byte for byte.
    on_disk: dict[str, bytes] = {}
    for top in (DOCS / PAGES_DIR, DOCS / ASSETS_DIR):
        if top.exists():
            for path in sorted(top.rglob("*")):
                if path.is_file():
                    on_disk[path.relative_to(DOCS).as_posix()] = path.read_bytes()
    for rel in sorted(set(result.files) | set(on_disk)):
        if rel not in on_disk:
            find(f"R8 docs/{rel}: missing; run `import_docs.py import`")
        elif rel not in result.files:
            find(f"R8 docs/{rel}: not produced by the importer (hand-added or stale)")
        elif on_disk[rel] != result.files[rel]:
            find(f"R8 docs/{rel}: differs from a re-import (hand-edited, or importer changed)")
    _b, region, _a = split_nav_region(MKDOCS_YML.read_text(encoding="utf-8"))
    if region != result.nav:
        find("R8 mkdocs.yml: hubzero nav region differs from a re-import")

    # R2: every published source page maps to exactly one output with the same title.
    pages = model.pages()
    expected = len(model.roots) + sum(1 for b in model.books if b.book in model.enabled
                                      for p in b.walk() if p.source)
    if len(pages) != expected:
        find(f"R2 page count {len(pages)} != expected {expected}")
    if final:
        if sorted(model.enabled) != sorted(b.book for b in model.books):
            find("R2 --final: not every book is enabled in import.yml")
        if len(pages) != 416:
            find(f"R2 --final: {len(pages)} pages, expected 416")
    for page in pages:
        data = on_disk.get(page.output)
        if data is None:
            continue
        meta, body = split_front_matter(data.decode("utf-8"))
        h1 = next((ln[2:].strip() for ln in body.splitlines() if ln.startswith("# ")), None)
        if h1 != page.title:
            find(f"R2 docs/{page.output}: H1 {h1!r} != source title {page.title!r} ({page.source})")
        # R6/R7: front-matter records status and provenance; the header comment is gone.
        hz = meta.get("hubzero") if isinstance(meta, dict) else None
        if not isinstance(hz, dict) or not all(k in hz for k in ("upstream", "commit", "status")):
            find(f"R6 docs/{page.output}: front-matter lacks hubzero.upstream/commit/status")
        elif hz["upstream"] != page.source or hz["commit"] != model.config["commit"]:
            find(f"R6 docs/{page.output}: hubzero.upstream/commit do not match the source")
        if meta.get("render_macros") is not False:
            find(f"R6 docs/{page.output}: render_macros: false is missing")
        if page.header and page.header.strip() in body:
            find(f"R7 docs/{page.output}: the source metadata header leaks into the body")
        if final and re.search(r"github\.com/hubzero/hubzero-cms/blob/[0-9a-f]{40}/docs/[^)\s\"'#]*\.md", body):
            find(f"R3 --final docs/{page.output}: still links a docs page on GitHub")

    # R11 (final): the home page card.
    if final and "hubzero/index.md" not in (DOCS / "index.md").read_text(encoding="utf-8"):
        find("R11 docs/index.md: no HUBzero card linking hubzero/index.md")

    # Built-site checks: R3 links and anchors, R4 images and alt, R5 API endpoints.
    if not (SITE / PAGES_DIR).is_dir():
        find("R3 site/hubzero/ missing: run `mkdocs build` before `check`")
        return findings
    parsed: dict[Path, SiteParser] = {}

    def parse(path: Path) -> SiteParser | None:
        if path not in parsed:
            if not path.is_file():
                return None
            parser = SiteParser()
            parser.feed(path.read_text(encoding="utf-8"))
            parsed[path] = parser
        return parsed[path]

    for page in pages:
        html_path = site_path_for(page.output)
        doc = parse(html_path)
        if doc is None:
            find(f"R2 {html_path.relative_to(ROOT)}: not built")
            continue
        where = html_path.relative_to(ROOT).as_posix()
        for href in doc.links:
            if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", href) or href.startswith("//"):
                continue
            path_part, _, fragment = href.partition("#")
            path_part = unquote(path_part.split("?", 1)[0])
            if not path_part:
                target = html_path
            elif path_part.startswith("/"):
                target = SITE / path_part.lstrip("/")
            else:
                target = (html_path.parent / path_part).resolve()
            if target.is_dir() or path_part.endswith("/"):
                target = target / "index.html"
            if not target.exists():
                find(f"R3 {where}: link {href!r} does not resolve")
                continue
            if fragment and target.suffix == ".html":
                other = parse(target)
                if other is not None and unquote(fragment) not in other.ids:
                    find(f"R3 {where}: anchor {href!r} does not exist")
        for src_attr, alt in doc.images:
            if not alt or not alt.strip():
                find(f"R4 {where}: image {src_attr!r} has no alt text")
            if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", src_attr) or src_attr.startswith("//"):
                continue
            target = (SITE / src_attr.lstrip("/")) if src_attr.startswith("/") else (html_path.parent / src_attr).resolve()
            if not target.is_file():
                find(f"R4 {where}: image {src_attr!r} does not exist")
        if page.source and page.source.startswith("docs/reference/api/"):
            want = [ln[3:].strip() for ln in page.body.splitlines()
                    if ln.startswith("## ") and ln[3:].split(" ", 1)[0] in HTTP_METHODS]
            have = {text: hid for hid, text in doc.h2}
            for endpoint in want:
                if not have.get(endpoint):
                    find(f"R5 {where}: endpoint {endpoint!r} not rendered as an h2 with an id")
    return findings


